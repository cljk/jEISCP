package de.csmp.jeiscp.eiscp;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import org.junit.Test;

/**
 * Writes {@code target/EiscpCommmandsConstants.java} from the YAML catalogue; copy it over {@link #SOURCE} by hand.
 * Not part of a plain {@code mvn test} because of its name: run {@code mvn test -Dtest=EiscpCommandsParserConstGenerator}.
 */
public class EiscpCommandsParserConstGenerator {

	static final Path SOURCE = Path.of("src/main/java/de/csmp/jeiscp/eiscp/EiscpCommmandsConstants.java");

	@Test
	public void generateConstFile() throws Exception {
		Path target = Path.of("target/EiscpCommmandsConstants.java");
		Files.writeString(target, generate(), StandardCharsets.UTF_8);
		System.out.println("wrote to " + target);
	}

	static String generate() {
		StringBuilder sb = new StringBuilder();
		sb.append("package " + EiscpCommandsParserConstGenerator.class.getPackage().getName() + ";\n\n\n");
		sb.append("/**\n");
		sb.append(" * GENERATED FILE\n");
		sb.append(" * do not modify\n");
		sb.append(" * \n");
		sb.append(" * generated by " + EiscpCommandsParserConstGenerator.class.getName() + "\n");
		sb.append(" */\n");
		sb.append("\n");
		sb.append("public class EiscpCommmandsConstants {\n\n");

		Map<String, CommandBlock> idToCommandBlockMap = EiscpCommandsParser.getIdToCommandBlockMap();
		Set<String> sortedIds = new TreeSet<String>(idToCommandBlockMap.keySet());

		for (String cbid : sortedIds) {
			CommandBlock cmdBlock = idToCommandBlockMap.get(cbid);
			writeEntry(sb, cmdBlock);

			Map<String, Command> idToCommandMap = new HashMap<String, Command>();
			for (Command cmd : cmdBlock.values) {
				idToCommandMap.put(cmd.getIdentifier(), cmd);
			}

			for (String cid : new TreeSet<String>(idToCommandMap.keySet())) {
				writeEntry(sb, idToCommandMap.get(cid));
			}
		}
		sb.append("}");
		return sb.toString();
	}

	private static void writeEntry(StringBuilder sb, Command cmd) {
		String cid = cmd.getIdentifier();
		sb.append("/**\n");
		sb.append(" * ISCP Command: " + cmd.getIscpCommand() + "\n");
		sb.append(" * " + cmd.getDescription() + "\n */\n");

		String constId = constantName(cid);
		sb.append("public static final String " + constId + "_ID = \"" + cid + "\";\n");
		sb.append("public static final String " + constId + "_ISCP = \"" + cmd.getIscpCommand() + "\";\n");
		sb.append("\n");
	}

	private static void writeEntry(StringBuilder sb, CommandBlock cmdBlock) {
		sb.append("/**\n");
		sb.append(" * CommandBlock\n");
		sb.append(" * ISCP Command prefix: " + cmdBlock.getCommand() + "\n");
		sb.append(" * " + cmdBlock.getDescription() + "\n */\n");

		String constId = constantName(cmdBlock.getName());
		sb.append("public static final String " + constId + "_ID = \"" + cmdBlock.getName() + "\";\n");
		sb.append("public static final String " + constId + "_ISCP = \"" + cmdBlock.getCommand() + "\";\n");
		sb.append("\n");
	}

	private static String constantName(String id) {
		String constId = id.replaceAll("-", "_").replaceAll("::", "_");
		if (constId.startsWith("1")) {
			constId = "_" + constId;
		}
		return constId.toUpperCase();
	}
}
